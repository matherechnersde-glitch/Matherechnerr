export function calculateHoaiTableFee(costs: number, zone: number, rate: number) {
  if (costs < 25000 || costs > 25000000) throw new RangeError('HOAI table range');
  if (!Number.isInteger(zone) || zone < 0 || zone > 4) throw new RangeError('HOAI zone');
  if (rate < 0 || rate > 1) throw new RangeError('HOAI rate');
  let upperIndex = TABLE.findIndex((row) => row[0] >= costs);
  if (upperIndex === 0) upperIndex = 1;
  const lower = TABLE[upperIndex - 1];
  const upper = TABLE[upperIndex];
  const position = (costs - lower[0]) / (upper[0] - lower[0]);
  const lowerColumn = 1 + zone * 2;
  const upperColumn = lowerColumn + 1;
  const lowerValue = lower[lowerColumn] + position * (upper[lowerColumn] - lower[lowerColumn]);
  const upperValue = lower[upperColumn] + position * (upper[upperColumn] - lower[upperColumn]);
  return lowerValue + (upperValue - lowerValue) * rate;
}
